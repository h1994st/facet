"""Download pinned fonts, subset/slice them to WOFF2, and write src/css/30-fonts.css.

uv run fonts/build.py      (network; downloads cached in fonts/.cache/)
"""

import hashlib
import io
import json
import tomllib
import urllib.request
import zipfile
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / "fonts/.cache"
OUT = ROOT / "src/fonts"
CSS = ROOT / "src/css/30-fonts.css"
LATIN = (
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,"
    "U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"
)
# Box drawing and block elements, for the mono face only: tree output and ASCII art keep one
# font's widths instead of falling back to the system's mono.
BOXES = ",U+2500-259F"
FILES = {"Geist": "geist", "Geist Mono": "geist-mono", "Source Serif 4": "source-serif-4"}


def fetch(url: str, sha: str) -> bytes:
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / hashlib.sha256(url.encode()).hexdigest()[:16]
    if not path.exists():
        path.write_bytes(urllib.request.urlopen(url).read())
    data = path.read_bytes()
    assert hashlib.sha256(data).hexdigest() == sha, f"checksum mismatch: {url}"
    return data


def parse_range(r: str) -> list[int]:
    cps = []
    for part in r.split(","):
        part = part.strip().removeprefix("U+")
        lo, _, hi = part.partition("-")
        cps.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    return cps


def woff2(font_bytes: bytes, unicodes: list[int]) -> bytes | None:
    font = TTFont(io.BytesIO(font_bytes))
    cmap = set(font.getBestCmap())
    keep = [c for c in unicodes if c in cmap]
    if not keep:
        return None
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=keep)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return buf.getvalue()


def face(family: str, file: str, weight: str, urange: str) -> str:
    return (
        f'@font-face {{\n  font-family: "{family}";\n  font-style: normal;\n'
        f"  font-weight: {weight};\n  font-display: swap;\n"
        f'  src: url("fonts/{file}") format("woff2");\n  unicode-range: {urange};\n}}\n'
    )


def main() -> None:
    src = tomllib.loads((ROOT / "fonts/sources.toml").read_text())
    if OUT.exists():
        for f in OUT.iterdir():
            f.unlink()
    OUT.mkdir(parents=True, exist_ok=True)
    out = ["/* Generated by fonts/build.py; do not edit. */\n@layer facet.base {\n"]
    for key in ("geist", "source-serif"):
        z = zipfile.ZipFile(io.BytesIO(fetch(src[key]["url"], src[key]["sha256"])))
        (OUT / f"LICENSE-{key}.txt").write_bytes(z.read(src[key]["license"]))
        for family, member in src[key]["members"].items():
            urange = LATIN + BOXES if family == "Geist Mono" else LATIN
            data = woff2(z.read(member), parse_range(urange))
            name = f"{FILES[family]}.woff2"
            (OUT / name).write_bytes(data)
            out.append(face(family, name, "100 900", urange))
    sc = src["noto-serif-sc"]
    data = fetch(sc["url"], sc["sha256"])
    lic = urllib.request.urlopen(sc["license_url"]).read()
    (OUT / "LICENSE-noto-serif-sc.txt").write_bytes(lic)
    for i, r in enumerate(json.loads((ROOT / "fonts/cjk-slices.json").read_text())):
        w = woff2(data, parse_range(r))
        if w is None:
            continue
        name = f"noto-serif-sc-600.{i:03d}.woff2"
        (OUT / name).write_bytes(w)
        out.append(face("Noto Serif SC", name, "600", r))
    out.append("}\n")
    CSS.write_text("".join(out))


if __name__ == "__main__":
    main()
