"""Build dist/ from src/: concatenate CSS in path order, copy JS, cats, fonts and icons, and
generate dist/icons.css from src/icons/.

uv run scripts/build.py
"""

import shutil
import tomllib
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]

ICON_BASE = """\
  .f-icon {
    display: inline-block;
    inline-size: 1em;
    block-size: 1em;
    flex: none;
    background-color: currentColor;
    -webkit-mask: var(--f-icon) center / contain no-repeat;
    mask: var(--f-icon) center / contain no-repeat;
    print-color-adjust: exact;
    vertical-align: -0.125em;
  }
"""


def icons_css(src_dir: Path, aliases: dict[str, str]) -> str:
    """One mask rule per src/icons/<name>.svg; an alias shares its target's rule."""
    rules = []
    for path in sorted(src_dir.glob("*.svg")):
        name = path.stem
        selectors = [f".f-icon--{name}"] + [
            f".f-icon--{a}" for a, t in aliases.items() if t == name
        ]
        uri = "data:image/svg+xml," + quote(path.read_text(), safe=" /:=.,-")
        rules.append(f'  {", ".join(selectors)} {{\n    --f-icon: url("{uri}");\n  }}\n')
    return (
        "/* Generated by scripts/build.py from src/icons/: Simple Icons (CC0) and Bootstrap Icons\n"
        "   (MIT); licenses in icons/. Brand names and marks belong to their owners. */\n"
        "@layer facet.components {\n" + ICON_BASE + "".join(rules) + "}\n"
    )


def build(root: Path = ROOT) -> None:
    src, dist = root / "src", root / "dist"
    if dist.exists():
        shutil.rmtree(dist)
    dist.mkdir()
    parts = []
    for path in sorted((src / "css").rglob("*.css")):
        rel = path.relative_to(src / "css").as_posix()
        parts.append(f"/* src/css/{rel} */\n{path.read_text().strip()}\n")
    (dist / "facet.css").write_text("\n".join(parts))
    for name in ("js", "cast", "fonts", "icons"):
        if (src / name).exists():
            shutil.copytree(src / name, dist / name)
    if (src / "icons").exists():
        aliases = tomllib.loads((root / "icons" / "sources.toml").read_text())["aliases"]
        (dist / "icons.css").write_text(icons_css(src / "icons", aliases))


if __name__ == "__main__":
    build()
